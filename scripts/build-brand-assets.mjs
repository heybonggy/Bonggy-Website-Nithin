/**
 * Builds every brand asset the site serves, from the same geometry the
 * components draw (DESIGN.md §7.1, §7.21). Nothing here is hand-drawn: if the
 * mark or a bot look changes, re-run this and everything follows.
 *
 *   node scripts/build-brand-assets.mjs
 *
 * Writes into public/, and regenerates src/content/bot-palette.ts from the
 * tokens in globals.css so the OG images and the downloadable bot files use the
 * same colours the site does.
 *
 * Raster icons are paper tiles: an opaque white square with the ink planet on
 * it. A transparent ink PNG vanishes against a dark tab strip or launcher,
 * which is exactly what the old 48px favicon did.
 */
// Registered before any aliased import is resolved.
import "./alias-hook.mjs";

import { mkdir, writeFile, readFile, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import opentype from "opentype.js";

import {
  INK,
  PAPER,
  RING,
  logoSvgDocument,
  logoSvgInner,
  paperTileSvg,
} from "../src/lib/logo-geometry.ts";
import { botSvg } from "../src/lib/bot-geometry.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");
const FONT = join(ROOT, "src/assets/fonts/Geist-Medium.ttf");
const GLOBALS = join(ROOT, "src/app/globals.css");
const PALETTE_FILE = join(ROOT, "src/content/bot-palette.ts");

/** White for the dark-surface variants of the mark. */
const SNOW = "#ffffff";

const written = [];

async function write(relative, data) {
  const path = join(PUBLIC, relative);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
  written.push(relative);
}

const svgBuffer = (svg) => Buffer.from(svg, "utf8");

/** Rasterise an SVG at an exact pixel size. */
const png = (svg, size) =>
  sharp(svgBuffer(svg), { density: 384 }).resize(size, size, { fit: "fill" }).png().toBuffer();

/* ------------------------------- bot palette ------------------------------- */

/**
 * The bot colours live in globals.css as the single source. Reading them here
 * and writing a TS module keeps the OG images and the downloads in step with
 * the site without anyone copying hex by hand.
 */
async function buildPalette() {
  const css = await readFile(GLOBALS, "utf8");
  const colors = {};
  const re = /--bot-([a-z]+)-(disc|ink|tint|face|ring):\s*([^;]+);/g;
  let m;
  while ((m = re.exec(css))) {
    const [, name, slot, value] = m;
    const bot = (colors[name] ??= {});
    // Light is declared first; the .dark block below it re-declares the same
    // names. The downloads and OG images are always on paper, so keep the
    // first value of each and ignore the dark override.
    bot[slot] ??= value.trim();
  }

  const names = Object.keys(colors);
  if (names.length === 0) throw new Error("no --bot-* tokens found in globals.css");

  const body = names
    .map(
      (name) =>
        `  ${name}: { disc: ${JSON.stringify(colors[name].disc)}, ring: ${JSON.stringify(
          colors[name].ring,
        )}, faceInk: ${JSON.stringify(colors[name].face)}, ink: ${JSON.stringify(
          colors[name].ink,
        )}, tint: ${JSON.stringify(colors[name].tint)} },`,
    )
    .join("\n");

  const file = `/**
 * GENERATED by scripts/build-brand-assets.mjs from the --bot-* tokens in
 * src/app/globals.css. Don't edit by hand; change the tokens and re-run.
 *
 * The light-theme values only. OG images and downloadable bot files are always
 * drawn on paper, and neither Satori nor a downloaded SVG can resolve a CSS
 * variable, so they need the colours as literals.
 *
 * This is the one file DESIGN.md §1's hue check exempts from the raw-hex rule.
 */
import type { Palette } from "@/lib/bot-geometry";

export type BotPalette = Palette & { ink: string; tint: string };

export const BOT_PALETTE: Record<string, BotPalette> = {
${body}
};

/** A bot colour's palette, falling back to graphite. */
export const paletteFor = (color: string): BotPalette =>
  BOT_PALETTE[color] ?? BOT_PALETTE.graphite;
`;
  await writeFile(PALETTE_FILE, file);
  return colors;
}

/* ----------------------------------- ico ----------------------------------- */

/**
 * An ICO container by hand: a 6-byte header, a 16-byte directory entry per
 * image, then the PNGs. Every ICO reader since Vista takes PNG payloads, and
 * the format is small enough not to be worth a dependency.
 */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // 1 = icon
  header.writeUInt16LE(images.length, 4);

  const entries = [];
  const payloads = [];
  let offset = 6 + images.length * 16;

  for (const { size, data } of images) {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0); // width (0 means 256)
    entry.writeUInt8(size >= 256 ? 0 : size, 1); // height
    entry.writeUInt8(0, 2); // palette count
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    entries.push(entry);
    payloads.push(data);
  }

  return Buffer.concat([header, ...entries, ...payloads]);
}

/* --------------------------------- lockup ---------------------------------- */

/**
 * The lockup: the mark plus "Bonggy" in Geist 500 at −0.02em, 10px apart at a
 * 24px mark (DESIGN.md §7.1).
 *
 * The wordmark is converted to outlines, so the file needs no font to render
 * and stays a few KB. Embedding the TTF instead would make each download about
 * 100KB of font nobody asked for.
 */
async function lockupSvg(ink) {
  const buf = await readFile(FONT);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

  // Everything is expressed at a 24px mark, then the viewBox scales it.
  const MARK = 24;
  const GAP = 10;
  const FONT_SIZE = 17; // the navbar's 1.0625rem
  const TRACKING = -0.02 * FONT_SIZE;

  // Letter by letter, so the −0.02em tracking is real rather than approximated.
  const path = new opentype.Path();
  let x = MARK + GAP;
  for (const ch of "Bonggy") {
    const glyph = font.charToGlyph(ch);
    const glyphPath = glyph.getPath(x, 0, FONT_SIZE);
    path.extend(glyphPath);
    x += (glyph.advanceWidth / font.unitsPerEm) * FONT_SIZE + TRACKING;
  }

  const width = x - TRACKING;
  // The cap height sits the wordmark optically centred against the mark.
  const capHeight = (font.tables.os2?.sCapHeight ?? 700) / font.unitsPerEm * FONT_SIZE;
  const baseline = MARK / 2 + capHeight / 2;

  const markScale = MARK / 256;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width.toFixed(2)} ${MARK}" ` +
    `width="${width.toFixed(2)}" height="${MARK}" role="img" aria-label="Bonggy">` +
    `<g transform="scale(${markScale})">` +
    // The mark is drawn at the lockup's small size, so it uses the heavier ring.
    logoSvgInner({ ink, page: "none", ring: RING.ui }) +
    `</g>` +
    `<path transform="translate(0 ${baseline.toFixed(2)})" d="${path.toPathData(2)}" fill="${ink}"/>` +
    `</svg>`
  );
}

/* ----------------------------------- run ----------------------------------- */

async function main() {
  const palette = await buildPalette();

  /* Icons: paper tiles, so they read on dark surfaces. */
  const tiles = Object.fromEntries(
    await Promise.all(
      [16, 32, 48, 96, 180, 192, 512].map(async (size) => [size, await png(paperTileSvg(size), size)]),
    ),
  );

  await write("favicon.ico", ico([16, 32, 48].map((size) => ({ size, data: tiles[size] }))));
  await write("icon-96.png", tiles[96]);
  await write("icon-192.png", tiles[192]);
  await write("apple-touch-icon.png", tiles[180]);
  await write("icons/icon-512.png", tiles[512]);
  await write("brand/logo/bonggy-logo-512.png", tiles[512]);

  /**
   * The maskable icon keeps the planet inside the central 80%, because
   * launchers crop the rest away to whatever shape they use.
   */
  const maskable =
    `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 256 256">` +
    `<rect width="256" height="256" fill="${PAPER}"/>` +
    `<g transform="translate(38.4 38.4) scale(0.7)">` +
    logoSvgInner({ ink: INK, page: PAPER, ring: RING.icon }) +
    `</g></svg>`;
  await write("icons/icon-512-maskable.png", await png(maskable, 512));

  /**
   * The adaptive SVG favicon, moved from src/app/icon.svg unchanged: it swaps
   * to light ink inside dark browser chrome, which a raster tile can't do.
   */
  const adaptive = await readFile(join(ROOT, "src/app/icon.svg"), "utf8").catch(() =>
    readFile(join(PUBLIC, "icon.svg"), "utf8"),
  );
  await write("icon.svg", adaptive);

  /* The mark on its own, transparent, at the artwork's original ring. */
  for (const [name, ink] of [["black", INK], ["white", SNOW]]) {
    const svg = logoSvgDocument({ ink, page: "none", ring: RING.art });
    await write(`brand/logo/bonggy-mark-${name}.svg`, svgBuffer(svg));
    for (const size of [512, 1024]) {
      await write(
        `brand/logo/bonggy-mark-${name}-${size}.png`,
        await sharp(svgBuffer(svg), { density: 384 })
          .resize(size, size, { fit: "fill", background: "#00000000" })
          .png()
          .toBuffer(),
      );
    }

    await write(`brand/logo/bonggy-lockup-${name}.svg`, svgBuffer(await lockupSvg(ink)));
  }

  /* Every bot's avatar, transparent, from its default look. */
  const { CATALOG } = await import("../src/content/bots.ts");
  for (const bot of CATALOG) {
    const colors = palette[bot.look.color];
    if (!colors) throw new Error(`no palette for ${bot.look.color}`);
    const paint = { disc: colors.disc, ring: colors.ring, faceInk: colors.face };
    const svg = botSvg(bot.look, paint, { size: 256, label: bot.name });
    await write(`brand/bots/${bot.slug}.svg`, svgBuffer(svg));
    for (const size of [256, 1024]) {
      await write(
        `brand/bots/${bot.slug}-${size}.png`,
        await sharp(svgBuffer(svg), { density: 384 })
          .resize(size, size, { fit: "contain", background: "#00000000" })
          .png()
          .toBuffer(),
      );
    }
  }

  // The old app-router icons are replaced by the explicit public/ ones.
  for (const stale of ["src/app/favicon.ico", "src/app/icon.svg", "src/app/apple-icon.tsx"]) {
    await rm(join(ROOT, stale), { force: true });
  }

  console.log(`brand assets: ${written.length} files`);
  for (const f of written) console.log(`  public/${f}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
